#!/usr/bin/env python
"""A2 — render `reports/benchmark_composition.md` from the pilot artifacts.

Until 2026-08-29 this report was written by hand.  When the corpus was replaced by v3.1
and `scripts/build_benchmark.sh` re-selected the pilot, the report stayed behind and went
on describing four v1 roots (`ds1_Uu09qKeIh1s_…` and friends) that no longer exist — the
same failure mode as `reports/reference_qc.md`.  It is now generated, and generated from
the build's own outputs only:

    data/benchmark/pilot.jsonl          the 30 benchmark texts
    data/benchmark/pilot_stats.json     selection pool, rejects, wpm, tokenizer hashes
    reports/benchmark_edits.json        every disfluency edit with its context
    reports/hidden_feasibility.{md,json}  §7.1, embedded verbatim
    configs/benchmark_pilot.yaml        the frozen recipe (thresholds, buckets, charset)

Nothing here is typed in by hand: every count, threshold and example is read from those
files, and §9 re-derives the benchmark contract (nesting, bucket membership, offsets,
token monotonicity) from `pilot.jsonl` itself and prints PASS/FAIL.

CPU only, no GPU, no model, no dataset scan beyond `os.path.exists` on the human audio.

    python src/benchmark/composition_report.py
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import json
import os
import time

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


# --------------------------------------------------------------------------- helpers
def jload(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def mtime(path):
    return time.strftime("%Y-%m-%d %H:%M", time.localtime(os.path.getmtime(path)))


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def num(v, n=2, dash="—"):
    if v is None:
        return dash
    if isinstance(v, float):
        return f"{v:.{n}f}"
    return str(v)


def wpm(rec):
    d = rec.get("human_duration_sec")
    if not d:
        return None
    return float(rec["words"]) * 60.0 / float(d)


# ------------------------------------------------------------------------ the report
def build(a):
    recs = jsonl(a.pilot)
    stats = jload(a.stats)
    edits = jload(a.edits)
    cfg = yaml.safe_load(open(a.config, encoding="utf-8"))
    dcfg = yaml.safe_load(open(a.dataset_config, encoding="utf-8"))
    feas_md = open(a.feasibility, encoding="utf-8").read().strip()
    feas = jload(a.feasibility_json)

    dcfg_root = dcfg.get("root") or dcfg.get("dataset", {}).get("root")
    dcfg_ver = dcfg.get("version") or dcfg.get("dataset", {}).get("version")
    P = cfg["dataset_roots"]
    buckets = cfg["buckets"]
    bnames = sorted(buckets)
    by_root = collections.defaultdict(dict)
    for r in recs:
        by_root[r["root_id"]][r["bucket"]] = r
    roots = sorted(by_root, key=lambda k: (0 if k.startswith("ds") else 1, k))
    ds_roots = [k for k in roots if by_root[k][bnames[0]]["source"] == "dataset"]
    ex_roots = [k for k in roots if k not in ds_roots]
    ds_recs = [r for r in recs if r["source"] == "dataset"]

    L = []
    A = L.append

    # ------------------------------------------------------------------------ header
    A("# Benchmark composition — pilot (PLAN.md §7)\n")
    A(f"**Owner:** A2 · **Generated:** {time.strftime('%Y-%m-%d %H:%M')} by "
      f"`src/benchmark/composition_report.py` · **Dataset:** `{dcfg_ver}` "
      f"(`{dcfg_root}`, `configs/dataset.yaml`)\n")
    A(f"**Artifact:** `{a.pilot}` — {len(recs)} texts, "
      f"sha256 `{sha256_file(a.pilot)}`.\n")
    A("Every number below is read from the files in the table; nothing is typed in by "
      "hand. This report is regenerated by `bash scripts/build_benchmark.sh` after every "
      "rebuild of the benchmark — a hand-written version of it survived the v3.1 corpus "
      "switch describing four roots that no longer existed, which is why it is generated "
      "now.\n")
    A("| input | written |")
    A("|---|---|")
    inputs = [a.pilot, a.stats, a.edits, a.feasibility, a.feasibility_json, a.config]
    for p in inputs:
        A(f"| `{p}` | {mtime(p)} |")
    A("")
    # Only the DERIVED artifacts must keep up with pilot.jsonl; the config is an input to
    # the build and is expected to be older.
    derived = [a.stats, a.edits, a.feasibility, a.feasibility_json]
    stale = [p for p in derived
             if os.path.getmtime(p) < os.path.getmtime(a.pilot) - 1]
    if stale:
        A("> **Warning — derived inputs older than the benchmark itself:** "
          + ", ".join(f"`{p}`" for p in stale)
          + ". They were produced for a previous build of `pilot.jsonl`; re-run "
            "`bash scripts/build_benchmark.sh` before quoting the sections that use "
            "them.\n")

    # -------------------------------------------------------------------- 1. what it is
    A("## 1. What the pilot is\n")
    vpt = cfg["pilot"]["voices_per_text"]
    A(f"{len(roots)} root documents × {len(bnames)} nested prefixes "
      f"{bnames[0]}–{bnames[-1]} = **{len(recs)} benchmark texts**; with A5's {vpt} unseen "
      f"voices that is {len(recs) * vpt} generations per checkpoint (PLAN §7.4).\n")
    A(f"* **{len(ds_roots)} dataset roots** (genres "
      + ", ".join(str(by_root[k][bnames[0]]["genre"]) for k in ds_roots)
      + f"), each a *single continuous {P['source_manifest'].rsplit('/', 1)[-1].split('.')[0]} "
      f"segment* of ≥ {P['min_duration_sec']} s with "
      f"`asr_consistency ≥ {P['min_asr_consistency']}` and `is_single_speaker = True`, from "
      f"**{len({by_root[k][bnames[0]]['channel_id'] for k in ds_roots})} different "
      f"channels** and "
      f"{len({by_root[k][bnames[0]]['video_id'] for k in ds_roots})} different videos. "
      "All five prefixes are literal prefixes of one continuous stretch of one human "
      "recording, starting at `human_offset_start`, so "
      + " ⊂ ".join(bnames)
      + " and every prefix has real human audio, a real human duration and an ASR error "
        "floor.")
    est_src = by_root[ex_roots[0]][bnames[0]]["human_duration_source"] if ex_roots else ""
    A(f"* **{len(ex_roots)} constructed roots** (genres "
      + ", ".join(str(by_root[k][bnames[0]]["genre"]) for k in ex_roots)
      + ") written for this benchmark. They have **no human audio** "
        "(`human_audio_path: null`, `human_offset_*: null`); their human duration is "
        f"*estimated* as `words / wpm × 60` with **wpm = "
        f"{stats['dev_median_wpm']:.3f}**, the median words-per-minute over the "
        f"{stats['n_dev_rows']} rows of `{P['source_manifest']}` (`{est_src}`).\n")
    A("Bucket = **human** reference duration (PLAN §7.1): "
      + ", ".join(f"{b} {buckets[b][0]}–{buckets[b][1]} s" for b in bnames)
      + f". All {len(recs)} texts land inside their bucket (§9, and "
        "`tests/test_benchmark.py::test_bucket_membership_by_human_duration`).\n")
    if stats.get("root_fallback_used"):
        A(f"> **The `root_fallback: {stats['root_fallback']}` rule was used.** dev did not "
          f"offer {cfg['pilot']['n_dataset_roots']} channels with an eligible root, so the "
          "pool was topped up with the next-best roots from *other videos* of the eligible "
          "channels — one root per video, never two from one video. The dataset roots "
          "therefore do **not** all come from different channels; the per-root table in §3 "
          "shows which channel each belongs to.\n")
    else:
        A(f"The `root_fallback: {stats['root_fallback']}` rule of "
          "`configs/benchmark_pilot.yaml` (dev may hold as few as 2 channels under split "
          "rule v3) was **not needed**: `pilot_stats.json` records "
          "`root_fallback_used = false`, i.e. every dataset root comes from a different "
          "channel.\n")

    # ------------------------------------------------------------ 2. how roots chosen
    A("## 2. How the roots were chosen (frozen, reproducible)\n")
    A(f"`{a.config}`, implemented in `src/benchmark/build_pilot.py`:\n")
    A(f"1. **Eligibility** over `{P['source_manifest']}`: "
      f"`duration_sec ≥ {P['min_duration_sec']}`, "
      f"`asr_consistency ≥ {P['min_asr_consistency']}`, `is_single_speaker`, word-group "
      f"timestamps present (`{P['timestamp_source']}`); text from `{P['text_source']}`.")
    ps = P["prefix_start"]
    A(f"2. **Where the chain starts** (`prefix_start: {ps['method']}`). A YouTube recording "
      "almost never opens with the genre it represents: it opens with a microphone check, a "
      f"greeting roll-call or a channel promo, and {bnames[0]} is only "
      f"{buckets[bnames[0]][0]}–{buckets[bnames[0]][1]} s, so that block would *become* the "
      f"{bnames[0]} benchmark text. Frozen rule: the chain starts at the **first sentence "
      f"boundary such that the next `lookahead_sec = {ps['lookahead_sec']}` seconds match "
      f"none of the {len(ps['opening_patterns'])} `opening_patterns`** (three families: A/V "
      "check, audience/stream address, greeting and channel promo). If no such boundary "
      f"exists at or before `max_start_sec = {ps['max_start_sec']}`, the root is "
      "**disqualified** — it is never silently started at 0. On this build the starts are "
      + ", ".join(f"`{c['sample_id']}` {c['prefix_start_sec']:.2f} s"
                  for c in stats["pool"]) + ".")
    A(f"3. **Charset**: **no digit** (`forbid_digits: {P['forbid_digits']}`) and no Latin "
      f"token outside the frozen {len(P['latin_transliteration'])}-entry transliteration "
      "table anywhere in the selection window. Digits and unknown Latin **disqualify** a "
      "root instead of being silently rewritten, because A3 froze the CosyVoice text "
      "frontend to `\"\"`: it has no Russian number expansion, so a digit would be read "
      "character-wise, and Russian case agreement for numerals cannot be produced "
      "deterministically (`reports/normalization_spec.md` §5). §7.1 measures what this "
      "costs.")
    A("4. **A cut point in every bucket**: a word group whose (edited) text ends on "
      "sentence punctuation and whose end time — *measured from the prefix start* — falls "
      f"inside the bucket, strictly after the previous bucket's cut "
      f"(`prefix_cut: {P['prefix_cut']}`).")
    A(f"5. **One root per channel** (`root_per_channel: {P['root_per_channel']}`) — the one "
      f"with the lowest filler density over its `selection_window_sec = "
      f"{P['selection_window_sec']}` seconds **after** the prefix start (the PLAN §6.5 "
      f"rule); if fewer channels than roots are available, `root_fallback: "
      f"{P['root_fallback']}` tops the pool up from other videos of the same channels.")
    ga = P["genre_assignment"]
    A(f"6. **Genre assignment**: brute force over injective assignments of the pool to "
      f"genres {min(ga['features'])}–{max(ga['features'])} "
      f"(`method: {ga['method']}`), maximising the sum of z-scored genre features "
      "(Table D). Filler-density penalty λ = "
      f"{ga['filler_penalty_lambda']} — genre fit is a contract requirement (PLAN §7.3), "
      "density already decided step 5, and density is the tie-break.\n")
    rej = stats.get("rejects", {})
    n_after_dur = stats["n_dev_rows"] - rej.get("duration", 0)
    A(f"**Result of this run.** {stats['n_dev_rows']} dev rows → "
      f"{n_after_dur} pass the duration filter → **{stats['n_eligible_roots']} eligible "
      f"roots in {stats['n_eligible_channels']} channels** (rejects: "
      + ", ".join(f"{v} {k}" for k, v in sorted(rej.items()))
      + f") → **{stats['n_pool_roots']} roots in the pool** (one per channel, lowest filler "
      f"density). {len(ds_roots)} of them are used as dataset roots. The pilot's genre "
      "labels are *relative* labels inside that pool, not absolute genre judgments.\n")

    # ------------------------------------------------------------------ 3. composition
    A("## 3. Composition\n")
    A("### Table A — root documents\n")
    A("| root_id | genre | source | channel | video | sample_id | split | asr_cons | "
      f"root dur s | prefix start s | filler /100w | edits in window | "
      f"words removed by {bnames[-1]} |")
    A("|---|---:|---|---|---|---|---|---:|---:|---:|---:|---:|---:|")
    pool_by_sid = {c["sample_id"]: c for c in stats["pool"]}
    for k in roots:
        r = by_root[k][bnames[-1]]
        e = edits.get(k, {})
        pool = pool_by_sid.get(r.get("sample_id") or "", {})
        A(f"| `{k}` | {r['genre']} | {r['source']} | "
          f"{(r.get('channel_title') or '—').strip()} | "
          f"{(r.get('video_title') or '—').strip()[:48]} | "
          f"`{r.get('sample_id') or '—'}` | {r.get('split') or '—'} | "
          f"{num(float(r['asr_consistency']), 2) if r.get('asr_consistency') else '—'} | "
          f"{num(pool.get('duration_sec'))} | {num(e.get('prefix_start_sec'), 3)} | "
          f"{num(e.get('filler_density_per_100w'), 2)} | {len(e.get('edits', []))} | "
          f"{int(by_root[k][bnames[-1]]['n_words_removed'])} |")
    A("")

    A("### Table B — prefixes (bucket = HUMAN duration)\n")
    A("| text_id | bucket | human dur s | offsets s | words | chars | sentences | "
      "ref words | tokens | context occ. | edits | words removed | est floor ins. | "
      "sha256_text_tts |")
    A("|---|---|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|")
    for k in roots:
        for b in bnames:
            r = by_root[k][b]
            off = ("—" if r.get("human_offset_start") is None else
                   f"{float(r['human_offset_start']):.2f}–{float(r['human_offset_end']):.2f}")
            A(f"| `{r['text_id']}` | {b} | {float(r['human_duration_sec']):.2f} | {off} | "
              f"{r['words']} | {r['chars']} | {r['sentences']} | {r['ref_words']} | "
              f"{r['text_tts_tokens']} | {float(r['context_occupancy_est']):.3f} | "
              f"{r['n_disfluency_edits']} | {r['n_words_removed']} | "
              f"{num(r['est_floor_insertion_rate'] if r['est_floor_insertion_rate'] is None else float(r['est_floor_insertion_rate']), 4)} | "
              f"`{r['sha256_text_tts'][:12]}` |")
    A("")

    kinds = sorted({e["kind"] for d in edits.values() for e in d["edits"]})
    A("### Table C — edits by kind\n")
    if not kinds:
        A("The disfluency filter made **no edits at all** on this build: not one rule of "
          "`configs/disfluency_filter.yaml` fired on any of the selection windows.\n")
    else:
        A("| root_id | " + " | ".join(kinds) + " | total |")
        A("|---" * (len(kinds) + 2) + "|")
        tot = collections.Counter()
        for k in ds_roots:
            c = collections.Counter(e["kind"] for e in edits.get(k, {}).get("edits", []))
            tot.update(c)
            A(f"| `{k}` | " + " | ".join(str(c.get(x, 0)) for x in kinds)
              + f" | {sum(c.values())} |")
        A(f"| **all {len(ds_roots)} dataset roots** | "
          + " | ".join(f"**{tot.get(x, 0)}**" for x in kinds)
          + f" | **{sum(tot.values())}** |")
        A("| " + ", ".join(f"`{k}`" for k in ex_roots) + " | "
          + " | ".join("0" for _ in kinds) + " | 0 |")
        A("")
        A(f"All {sum(tot.values())} edits are in `{a.edits}` with their character offsets "
          "and ±40 characters of context. Also recorded there per root: "
          + ", ".join(
              f"`{k}` {edits[k]['n_case_repairs']} case repairs / "
              f"{edits[k]['n_transliterations']} transliterations" for k in ds_roots)
          + ".\n")

    A("### Table D — selection pool (one root per eligible channel)\n")
    feat_names = sorted({f for c in stats["pool"] for f in c["features"]})
    A("| assigned genre | channel | sample_id | dur s | prefix start s | asr_cons | "
      "filler /100w | " + " | ".join(feat_names) + " |")
    A("|---:|---|---|---:|---:|---:|---:|" + "---:|" * len(feat_names))
    for c in sorted(stats["pool"], key=lambda c: c["assigned_genre"] or 99):
        A(f"| {c['assigned_genre']} | {c['channel_title'].strip()} | `{c['sample_id']}` | "
          f"{c['duration_sec']:.1f} | {c['prefix_start_sec']:.2f} | "
          f"{c['asr_consistency']:.2f} | {c['filler_density_per_100w']:.2f} | "
          + " | ".join(f"{c['features'][f]:.4f}" for f in feat_names) + " |")
    A("")

    if kinds:
        A("### Examples of each edit kind\n")
        for kind in kinds:
            ex = next((e for d in edits.values() for e in d["edits"] if e["kind"] == kind),
                      None)
            if ex:
                what = ("deleted" if not ex["replacement"]
                        else f"`{ex['surface']}` → `{ex['replacement']}`")
                A(f"* `{kind}` — {what} `{ex['surface']}` — "
                  f"{ex['context'].strip()}" if not ex["replacement"]
                  else f"* `{kind}` — {what} — {ex['context'].strip()}")
        A("")

    # --------------------------------------------------------- 4. disfluency + charset
    A("## 4. The disfluency rule and the charset rule\n")
    A(f"**Disfluency** (`{cfg['disfluency']['spec']}` ↔ "
      f"`{cfg['disfluency']['implementation']}`, asserted equal by `load_spec()`): "
      "hesitation sounds, discourse fillers with keep-contexts, multi-word fillers, "
      "immediate repeats, truncated words (prefix-of-next with a function-word guard, and "
      "trailing-hyphen forms), speech-restart bigrams, and stuttered onsets with an "
      "excluded-onset list. Everything is a rule over words; there are no per-document "
      "exception lists and no hard-coded `sample_id`. The filter is applied **iteratively "
      "to a fixed point**, since deleting a filler can create a new immediate repeat. It is "
      f"applied to `{cfg['disfluency']['applied_to']}`; the untouched prefix is kept in "
      f"`{cfg['disfluency']['unedited_kept_in']}`.\n")
    tc = cfg["text_charset"]
    A(f"**Charset** (`{a.config}: text_charset` ↔ `disfluency.apply_charset`, applied "
      "inside `finalize()`, so it holds for `text_tts` *and* `text_tts_unedited`):\n")
    A(f"* the only punctuation that may survive is {' '.join('`' + c + '`' for c in tc['allowed_punctuation'])} "
      "(plus Cyrillic and space);")
    A(f"* every dash variant ({', '.join('`' + d + '`' for d in tc['dashes']['map_to_em_dash'])}) "
      "collapses to `—` (U+2014), and an em dash in sentence-initial position is deleted — "
      "the ASR does not produce Russian dialogue dashes, so one there came from a `--` "
      "artifact;")
    A(f"* **every quotation mark is deleted** ({len(tc['quotes']['delete'])} variants). The "
      "ASR's quotes are not trustworthy, and balancing them is not prefix-stable: a "
      "quotation opened in one bucket and closed in the next would have to be dropped from "
      "the shorter prefix and kept in the longer one, which breaks the nested-prefix "
      "contract of PLAN §7.2. The genre features are computed on the **raw** window text, "
      "before this pass, so genre 3 keeps its quotation evidence; and `text_ref` is "
      "unaffected, because the frozen normalizer strips quotes anyway;")
    A("* every apostrophe is deleted (``" + "".join(tc["apostrophes"]["delete"]) + "``);")
    A("* a sentence terminator glued to the next word gets one space.\n")
    A("Every rule looks only to the **left** of the character it changes, so the result for "
      "a prefix is the prefix of the result — that is what keeps "
      + " ⊂ ".join(bnames) + " intact, and `test_one_charset_no_quotes_no_stray_dashes` "
      "asserts both the charset and the idempotence of `finalize`.\n")
    ins = [float(r["est_floor_insertion_rate"]) for r in ds_recs]
    # the buckets are nested, so the longest prefix already contains every earlier edit
    rem = sum(int(by_root[k][bnames[-1]]["n_words_removed"]) for k in ds_roots)
    A("**Consequence for the ASR floor (A4 must read this).** The human audio still "
      "contains the fillers that were deleted from `text_tts`, so a floor measured against "
      f"`text_ref` counts them as insertions. Across the {len(ds_roots)} dataset roots "
      f"this build removed {rem} words from the longest ({bnames[-1]}) prefixes — the "
      "buckets are nested, so that count already contains every shorter prefix's edits — "
      "and `est_floor_insertion_rate` runs "
      f"{min(ins):.4f}–{max(ins):.4f} (median {sorted(ins)[len(ins)//2]:.4f}). The floor "
      "**must** be computed against exactly the `text_ref` in `pilot.jsonl`, and the "
      "primary content metric stays \"model WER − floor\" (PLAN §9.4). "
      "`text_tts_unedited` is kept in every record so the effect can be measured directly "
      "(run the floor twice and compare).\n")

    # ---------------------------------------------------------------------- 5. fields
    A(f"## 5. Fields in `{a.pilot}`\n")
    A("```")
    keys = list(recs[0].keys())
    line = ""
    for k in keys:
        if len(line) + len(k) + 1 > 78:
            A(line.rstrip())
            line = ""
        line += k + " "
    A(line.rstrip())
    A("```\n")
    tok = stats["tokenizer"]
    A("Field names follow PLAN §7.5 exactly; `scripts/run_generation.py` reads only "
      "`text_id`/`text_tts`, `scripts/run_evaluation.py` only "
      "`text_id`/`text_ref`/`human_audio_path`/`human_offset_start`/`human_offset_end`. "
      "`text_tts` is the **only** TTS input (punctuated, cased, cleaned, one charset), "
      f"`text_ref` the **only** WER reference (= normalize(text_tts, "
      f"`{stats['normalization_variant']}`), spec `{cfg['normalization']['spec']}`, "
      f"implementation `{cfg['normalization']['implementation']}`).\n")
    A(f"`text_tts_tokens` uses the model's own tokenizer — `{tok['class']}` over "
      f"`{tok['path']}` (CPU only, no weights; "
      + ", ".join(f"`{k}` sha256 `{v}…`" for k, v in sorted(tok["files_sha256"].items()))
      + f"). `context_occupancy_est` is the frozen pre-generation estimate of PLAN "
      f"§7.1/§9.6: `{cfg['context_occupancy']['formula']}` over the "
      f"{tok['context_window']}-position context. It reaches "
      f"**{max(float(r['context_occupancy_est']) for r in recs):.3f}** at "
      f"{bnames[-1]} — the benchmark fits, with "
      f"{100 * (1 - max(float(r['context_occupancy_est']) for r in recs)):.0f} % of the "
      "window left for a model that speaks slower than the human. The three quantities "
      "that need the model or the reference wav (prompt speech tokens, generated speech "
      "tokens, true context occupancy) belong to the run manifest (PLAN §10).\n")

    # --------------------------------------------------------------------- 6. rebuild
    A("## 6. Rebuild\n")
    A("```bash\nbash scripts/build_benchmark.sh\n```\n")
    A("which runs the normalizer equivalence check, `src/benchmark/build_pilot.py`, "
      "`src/benchmark/feasibility.py`, **this report** and `tests/test_benchmark.py`. "
      "The benchmark artifacts are byte-identical across runs and independent of the "
      "working directory or of a relative `--config`; this report differs only in its "
      "generation timestamp. Side artifacts: "
      + ", ".join(f"`{p}`" for p in (a.stats, a.edits, a.feasibility,
                                     a.feasibility_json)) + ".\n")

    # ------------------------------------------------------------------ 7. hidden set
    hs = cfg["hidden_set"]
    A("## 7. Rule for the future sealed hidden set (described, NOT built)\n")
    A(f"`data/benchmark/hidden.jsonl` — **{hs['n_roots']} roots × {len(hs['buckets'])} "
      f"buckets = {hs['n_roots'] * len(hs['buckets'])} texts**, "
      f"{hs['n_roots'] * len(hs['buckets']) * vpt} generations per checkpoint with A5's "
      f"{vpt} voices (PLAN §7.4). It is built **once**, {hs['build_when']}, and it is never "
      "looked at before the single hidden run (PLAN §3.5, §11.4).\n")
    A(f"Construction rule, to be implemented as `--split test --n-roots {hs['n_roots']}` on "
      "the same `src/benchmark/build_pilot.py`:\n")
    A(f"1. **Source: `{hs['source_manifest']}` only.** Test channels are disjoint from "
      "train and from dev by construction (split rule v3, `reports/split_rule_v3.md`), so "
      "hidden roots share no channel, video or speaker with anything the models saw, and "
      "none of them is a pilot root.")
    n_needed = feas.get("n_dataset_roots_needed_for_hidden_set", "?")
    tS1 = feas["test"]["variants"]["S1"]
    A(f"2. **Same eligibility filter as the pilot**, including `prefix_start` — but see "
      f"§7.1: under the frozen charset rule the test split yields only **{tS1['n_roots']} "
      f"eligible roots in {tS1['n_channels']} channels**, against the {n_needed} dataset "
      "roots the hidden set needs, so either one rule is relaxed (and the pilot rebuilt "
      f"with the same relaxation) or `root_fallback: {P['root_fallback']}` is used on the "
      "test side too.")
    A("3. **Genre coverage**: 2 roots per genre; the constructed genres are newly written "
      "documents, never reused from the pilot. Assignment by the same z-score procedure "
      "with λ = 0 and a distinct-channel constraint over all dataset slots.")
    A("4. **One root per channel**, lowest filler density first, exactly as in the pilot; "
      "if fewer distinct eligible channels exist than roots are needed, the shortfall is "
      "filled by the frozen fallback and the report says so explicitly rather than "
      "silently reusing a channel.")
    A("5. **Same disfluency filter, same charset rule, same normalizer, same seeds.** No "
      "rule may be re-tuned between the pilot and the hidden set; if the pilot forces a "
      "rule change, the change is made *before* the hidden set is built and the pilot is "
      "rebuilt with it.")
    A("6. **Sealing**: the file is written once, hashed (`sha256` of the file plus per-text "
      "`sha256_text_tts`), the hash is recorded in `reports/decisions.md`, and the file is "
      "not read by any tuning or checkpoint-selection code.")
    A("7. **No overlap check**: assert that no hidden `root_id`, `video_id` or `channel_id` "
      "appears in `data/benchmark/pilot.jsonl`, and that no hidden text is a prefix or "
      "superstring of a pilot text.\n")
    A("### 7.1 Feasibility measurement\n")
    A("Generated by `src/benchmark/feasibility.py` (run inside "
      f"`scripts/build_benchmark.sh`); the text below is `{a.feasibility}` verbatim, raw "
      f"numbers in `{a.feasibility_json}`.\n")
    A(feas_md)
    A("")

    # ----------------------------------------------------------------- 8. limitations
    A("## 8. Known limitations\n")
    A(f"* **The reference text is ASR output, not a human transcription.** `text_tts` comes "
      f"from `{P['text_source']}` and contains its errors; the models are asked to read "
      "them. Because the same text is the reference for every checkpoint and the "
      "human-audio ASR floor is measured on it, the paired comparison is unaffected, but "
      "**absolute** WER values include this noise. A light human proofreading pass on the "
      "hidden roots would remove it and is recommended.")
    A("* **Deleting the quote marks can make an ASR artifact more visible.** Nothing that "
      "is spoken changes and `text_ref` is unaffected, but a sentence whose quotation was "
      "already broken can end up reading oddly. It stays in: removing it would require a "
      "per-document exception.")
    A(f"* **Genre labels are relative.** The eligible pool is "
      f"{stats['n_eligible_channels']} channels; the genres are assigned inside that pool "
      "by measurable text features (Table D), not by editorial judgment. With a pool this "
      "small the assignment is a ranking, not a classification.")
    ex_wpm = [wpm(by_root[k][bnames[-1]]) for k in ds_roots]
    A(f"* **The {len(ex_roots)} constructed documents have no human audio**, therefore no "
      "ASR floor. Their absolute WER is not comparable with the dataset roots'; they are "
      "only comparable across checkpoints. Their human duration is an estimate at the dev "
      f"median rate ({stats['dev_median_wpm']:.3f} wpm), while the {len(ds_roots)} dataset "
      f"roots actually run at "
      + ", ".join(f"{w:.1f}" for w in ex_wpm)
      + f" wpm at {bnames[-1]} — the estimate is "
      + ("above every one of them" if stats["dev_median_wpm"] > max(ex_wpm)
         else "below every one of them" if stats["dev_median_wpm"] < min(ex_wpm)
         else "inside their range")
      + ". A model that reads the constructed documents at a different "
        "rate will produce audio of a different length, so the generated/reference duration "
        "ratio of PLAN §9.2 must be read with that caveat for the constructed genres; the "
        "bucket assignment itself is unaffected, since the bucket is defined by the nominal "
        "human duration recorded in the manifest.")
    A("* **The constructed genre-5 document contains Cyrillic acronyms** that the "
      "normalizer does not expand; a correct letter-by-letter reading may still be scored "
      "as an error. Kept deliberately — reading acronyms *is* that document's stress — but "
      "it inflates its absolute WER for every checkpoint equally.")
    A("* **Residual disfluencies exist.** The filter cannot see truncations that are not "
      "prefixes of the next word, or phrase-level restarts. Zero *rule* hits is what the "
      "test guarantees, not zero disfluencies.")
    A("* **`prefix_start` only removes the opening block.** A mic check or an audience "
      "address in the *middle* of a recording is not removed — the rule is about where the "
      "chain starts, not a content filter. `opening_patterns` is a lexicon, so it can also "
      "fire on ordinary content and push a start later than necessary; it never pushes it "
      f"earlier, and a root with no clean start ≤ {ps['max_start_sec']} s is dropped.")
    A("* **Speaking-rate confound between buckets is unavoidable**: because prefixes are "
      f"nested, {bnames[0]} always contains the beginning of a stretch, which is "
      "linguistically different from the middle of a talk. That is the design PLAN §7.2 "
      "asks for (nesting removes content confounding at the cost of position confounding).")
    A(f"* **Dev, not test.** The pilot roots come from "
      f"`{P['source_manifest']}` by design, so the pilot measures nothing about "
      "unseen-source generalisation on its own; that is what the hidden set is for.")
    devch = {by_root[k][bnames[0]]["channel_id"] for k in ds_roots}
    A(f"* **The pool is small.** {len(devch)} dev channels supply every dataset root "
      f"({stats['n_eligible_roots']} eligible roots existed in "
      f"{stats['n_eligible_channels']} channels), so a single channel's style carries a "
      "quarter of the dataset-side benchmark.\n")

    # ------------------------------------------------------------------ 9. validation
    A("## 9. Validation\n")
    A("Re-derived from `pilot.jsonl` by this script at generation time — these are not "
      "copied from a test log:\n")
    checks = []

    def chk(name, ok, detail=""):
        checks.append((name, bool(ok), detail))

    chk(f"{len(roots)} roots × {len(bnames)} buckets = {len(recs)} records",
        len(recs) == len(roots) * len(bnames) and all(
            set(by_root[k]) == set(bnames) for k in roots))
    chk("unique text_id", len({r["text_id"] for r in recs}) == len(recs))
    nest_tts = nest_ref = True
    for k in roots:
        for i in range(1, len(bnames)):
            if not by_root[k][bnames[i]]["text_tts"].startswith(
                    by_root[k][bnames[i - 1]]["text_tts"]):
                nest_tts = False
            if not by_root[k][bnames[i]]["text_ref"].startswith(
                    by_root[k][bnames[i - 1]]["text_ref"]):
                nest_ref = False
    chk("nested prefixes on text_tts", nest_tts)
    chk("nested prefixes on text_ref", nest_ref)
    inb = [r for r in recs
           if not (buckets[r["bucket"]][0] <= float(r["human_duration_sec"])
                   <= buckets[r["bucket"]][1])]
    chk("every human_duration_sec inside its bucket", not inb,
        "" if not inb else ", ".join(r["text_id"] for r in inb))
    mono = all(int(by_root[k][bnames[i]]["text_tts_tokens"])
               > int(by_root[k][bnames[i - 1]]["text_tts_tokens"])
               for k in roots for i in range(1, len(bnames)))
    chk("text_tts_tokens strictly increasing across buckets", mono)
    occ_ok = True
    for r in recs:
        want = (int(r["text_tts_tokens"])
                + cfg["context_occupancy"]["speech_token_rate_hz"]
                * float(r["human_duration_sec"])
                + cfg["context_occupancy"]["service_tokens"]) / tok["context_window"]
        if abs(want - float(r["context_occupancy_est"])) > 1e-6:
            occ_ok = False
    chk("context_occupancy_est equals the frozen formula", occ_ok)
    chk(f"dataset roots all from split '{ 'dev' }' with asr_consistency ≥ "
        f"{P['min_asr_consistency']}",
        all(r["split"] == "dev"
            and float(r["asr_consistency"]) >= P["min_asr_consistency"]
            for r in ds_recs))
    off_ok = all(abs((float(r["human_offset_end"]) - float(r["human_offset_start"]))
                     - float(r["human_duration_sec"])) < 1e-6 for r in ds_recs)
    chk("human_offset_end − human_offset_start = human_duration_sec (dataset)", off_ok)
    missing = [r["text_id"] for r in ds_recs if not os.path.exists(r["human_audio_path"])]
    chk("every human_audio_path exists on disk", not missing,
        "" if not missing else f"missing: {missing[:3]}")
    chk("constructed roots carry no human audio",
        all(r["human_audio_path"] is None
            for r in recs if r["source"] != "dataset"))
    chk("no digit in any text_tts", not any(any(c.isdigit() for c in r["text_tts"])
                                            for r in recs))
    chk("no quotation mark or apostrophe in any text_tts",
        not any(c in r["text_tts"] for r in recs
                for c in tc["quotes"]["delete"] + tc["apostrophes"]["delete"]))
    A("| check | result | detail |")
    A("|---|---|---|")
    for name, ok, detail in checks:
        A(f"| {name} | {'**PASS**' if ok else '**FAIL**'} | {detail or '—'} |")
    A("")
    n_fail = sum(1 for _, ok, _ in checks if not ok)
    A(f"**{len(checks) - n_fail}/{len(checks)} pass.**"
      + ("" if not n_fail else " **THE BENCHMARK IS BROKEN — do not use it.**") + "\n")
    A("The full contract is asserted by `tests/test_benchmark.py` (schema completeness per "
      "PLAN §7.5, nesting, bucket membership, sentence-final ending and capitalised start, "
      "zero disfluency-filter hits in `text_tts`, the one-charset rule and `finalize` "
      "idempotence, `prefix_start` re-derived from the word-group timestamps with the "
      "lookahead re-checked against the frozen patterns, token/occupancy bounds and "
      "monotonicity, `text_ref` equal to the frozen normalizer's output with "
      "`strict == lenient`, both YAML specs equal to their implementations):\n")
    A("```bash")
    A("bash scripts/build_benchmark.sh")
    A(".venv-eval/bin/python -m pytest tests/test_benchmark.py -q")
    A("python tests/test_benchmark.py"
      "   # stdlib runner")
    A("python src/eval/normalize_spec_ref.py")
    A("```")
    return "\n".join(L) + "\n", n_fail


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--pilot", default="data/benchmark/pilot.jsonl")
    ap.add_argument("--stats", default="data/benchmark/pilot_stats.json")
    ap.add_argument("--edits", default="reports/benchmark_edits.json")
    ap.add_argument("--feasibility", default="reports/hidden_feasibility.md")
    ap.add_argument("--feasibility-json", default="reports/hidden_feasibility.json")
    ap.add_argument("--config", default="configs/benchmark_pilot.yaml")
    ap.add_argument("--dataset-config", default="configs/dataset.yaml")
    ap.add_argument("--out", default="reports/benchmark_composition.md")
    ap.add_argument("--strict", action="store_true",
                    help="exit 1 if any §9 self-check fails")
    a = ap.parse_args(argv)
    os.chdir(ROOT)
    text, n_fail = build(a)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {a.out} ({len(text.splitlines())} lines); "
          f"{n_fail} failed self-check(s)")
    return 1 if (n_fail and a.strict) else 0


