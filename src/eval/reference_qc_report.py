    w("| voice_id | own segs | own cos min / mean / max | other test speakers | "
      "other cos median / p95 / max | nearest other speaker | mean(own) > max(other) | margin |")
    w("|---|---:|---|---:|---|---|---|---:|")
    for r in sorted(refs, key=lambda r: r["voice_id"]):
        cp = r.get("campplus")
        if not cp:
            w(f"| `{r['voice_id']}` | - | not computed | - | - | - | - | - |")
