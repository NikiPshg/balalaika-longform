NOT_VERIFIED = (
    "**NOT VERIFIED.** {reason} Until `src/eval/verify_references.py` is re-run against "
    "the current `data/references/references.jsonl`, this report has no verification "
    "evidence to publish here and prints none: re-run "
    "`python src/eval/verify_references.py` "
    "(step 3 of `scripts/rebuild_all.sh`), then regenerate this report."
)


def _mtime(path):
    return time.strftime("%Y-%m-%d %H:%M", time.localtime(os.path.getmtime(path)))


def load_verification(verify_path, refs_path, refs):
    """Return `(verification, status)` — the dict only if it is evidence for THESE refs.

    A verification JSON is admissible only when it exists, is newer than
    `references.jsonl`, and covers exactly the current `voice_id` set.  Otherwise this
    returns `({}, <NOT VERIFIED text>)` and every block that would cite it prints that
    text instead of numbers.  The v3.1 rebuild published the v1 file's numbers (4
    references, v1 source paths) as a `Verdict PASS` for a 3-reference set that had
    never been verified; refusing to print is the only safe default.
    """
    want = {r["voice_id"] for r in refs}
    if not os.path.exists(verify_path):
        return {}, NOT_VERIFIED.format(reason=f"`{verify_path}` does not exist.")
    if os.path.getmtime(verify_path) < os.path.getmtime(refs_path):
        return {}, NOT_VERIFIED.format(reason=(
            f"`{verify_path}` ({_mtime(verify_path)}) is older than `{refs_path}` "
            f"({_mtime(refs_path)}), so it was computed on a previous reference set."))
    ver = json.load(open(verify_path, encoding="utf-8"))
    got = set()
    for block, key in (("master", "rows"), ("f0", "rows"), ("campplus", "rows"),
                       ("loop", "natural_references")):
        for row in ((ver.get(block) or {}).get(key) or []):
            if row.get("voice_id"):
                got.add(row["voice_id"])
    if got != want:
        return {}, NOT_VERIFIED.format(reason=(
            f"`{verify_path}` covers {sorted(got)} but `{refs_path}` holds "
            f"{sorted(want)}."))
    return ver, ""


def fmt(v, n=3, dash="-"):
    if v is None:
        return dash
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, float):
        return f"{v:.{n}f}"
    return str(v)


def q(vals, p):
    return float(np.percentile(vals, p)) if len(vals) else float("nan")


