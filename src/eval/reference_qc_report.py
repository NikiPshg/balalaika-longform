    w("PLAN §9.5 allows campplus only as a *secondary* measure because the model itself "
      "conditions on it. The primary drift encoder must be independent of campplus; it "
      "will live in `src/eval/speaker_drift.py`, which is **planned, not yet written** — "
      "A5 part 2, blocked on an eval venv that can host an independent speaker encoder "
      "(see §6.1 and §9).")
